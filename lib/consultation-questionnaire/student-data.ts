export function studentQuestionnaireData(input: unknown): ConsultationQuestionnaireData {
  if (!input || typeof input !== "object" || Array.isArray(input)) return {};
  const source = input as Record<string, unknown>;
  const result: Record<string, unknown> = {};
  for (const key of STUDENT_FIELDS) {
    if (!Object.prototype.hasOwnProperty.call(source, key)) continue;
    const value = source[key];
    if (key !== "customBills" && typeof value === "string") result[key] = value;
    else if (["marketsTraded",
  "platformsUsed",
  "learningMethods",
  "preferredStudyTimes",
  "learningPrefs",
  "accountabilityPrefs",
  "devices",
  "focusAreas"].includes(key) && Array.isArray(value) && value.every(item => typeof item === "string")) result[key] = [...value];
    else if (key === "customBills" && Array.isArray(value)) result[key] = value.filter(item => item && typeof item.id === "string" && typeof item.name === "string" && typeof item.amount === "string").map(({ id, name, amount }) => ({ id, name, amount }));
  }
  return result as ConsultationQuestionnaireData;
}
